"""Print typed VM dispatch entries from the native CPU/CUDA C interfaces.

--check verifies the checked-in header; regeneration uses stdout so changes can
be reviewed before replacing src/bc_native_bindings.h.
"""
import argparse
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
SDK = ROOT / "TezzCorp_WebSites/tn_tezzcorp_com/download/sdk"
HEADER = SDK / "src/bc_native_bindings.h"
GPU_HEADER = SDK / "runtime/gpu_bindings.h"
EXPORT = re.compile(
    r"(?:TZ_CPU_EXPORT|TZ_EXPORT|TZ_GPU_EXPORT)\s+"
    r"(int64_t|int)\s+(tz_(?:cpu|gpu|cuda)_\w+)\s*\(([^)]*)\)"
)


def source_with_local_includes(path, seen=None):
    seen = set() if seen is None else seen
    path = path.resolve()
    if path in seen:
        return ""
    seen.add(path)
    source = path.read_text(encoding="utf-8")
    def include(match):
        nested = (path.parent / match.group(1)).resolve()
        if nested.is_relative_to((SDK / "lib").resolve()) and nested.is_file():
            return source_with_local_includes(nested, seen)
        return match.group(0)
    return re.sub(r'^\s*#\s*include\s*"([^"]+)"[^\n]*', include, source, flags=re.M)


def generate():
    lines = ["/* Generated by tools/generate_vm_bindings.py; do not edit by hand. */"]
    for filename, library in (("tzcpu_kernels.c", "TN_NATIVE_CPU"),
                              ("tzgpu_kernels.cu", "TN_NATIVE_GPU")):
        source = source_with_local_includes(SDK / "lib" / filename)
        matches = EXPORT.findall(source)
        if not matches:
            raise ValueError("No exported functions found in " + filename)
        for result, name, parameters in matches:
            types, values = [], []
            for index, parameter in enumerate(parameters.split(",")):
                parameter = parameter.strip()
                if not parameter or parameter == "void":
                    continue
                kind = parameter.split()[0]
                convert = {"int64_t": "tn_vm_integer", "double": "tn_vm_double",
                           "float": "tn_vm_float"}.get(kind)
                if not convert or len(parameter.split()) != 2:
                    raise ValueError("Unsupported native signature: " + name + " " + parameter)
                types.append(kind)
                values.append(f"{convert}(args[{index}])")
            lines.append(f"TN_VM_BIND({library}, {name}, {result}, {len(types)}, "
                         f"({', '.join(types) or 'void'}), ({', '.join(values)}))")
    return "\n".join(lines) + "\n"


def generate_gpu():
    lines = ["/* Generated by tools/generate_vm_bindings.py --gpu; do not edit by hand. */"]
    source = source_with_local_includes(SDK / "lib/tzgpu_kernels.cu")
    for result, name, parameters in EXPORT.findall(source):
        declarations, values = [], []
        for parameter in parameters.split(","):
            parameter = parameter.strip()
            if not parameter or parameter == "void":
                continue
            words = parameter.split()
            if len(words) != 2 or words[0] not in ("int64_t", "double", "float"):
                raise ValueError("Unsupported GPU signature: " + name + " " + parameter)
            declarations.append(" ".join(words))
            values.append(words[1])
        unavailable = 0 if name in ("tz_cuda_backend_kind", "tz_cuda_device_count", "tz_cuda_malloc",
                                    "tz_cuda_mem_free", "tz_cuda_mem_total") else -1
        lines.append(f"TN_GPU_BIND({name}, {result}, ({', '.join(declarations) or 'void'}), "
                     f"({', '.join(values)}), {unavailable})")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--gpu", action="store_true", help="print the typed lazy GPU bridge declarations")
    args = parser.parse_args()
    expected = generate_gpu() if args.gpu else generate()
    if args.check:
        for header, text in ((HEADER, generate()), (GPU_HEADER, generate_gpu())):
            if not header.is_file() or header.read_text(encoding="utf-8") != text:
                sys.exit(str(header) + " is stale; regenerate with tools/generate_vm_bindings.py")
        print("VM native dispatch and lazy GPU signatures match the C interfaces")
    else:
        sys.stdout.write(expected)
